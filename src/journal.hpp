#pragma once

// ============================================================
//  Journal —— 回滚日志（阶段 5）
//
//  ★ 阶段 5 的核心文件 ★
//
//  【它解决的问题】
//  阶段 3/4 里，改一页就是改缓存里那 4096 个字节，攒着，
//  到时候一起写回文件。程序正常跑完时这没问题，但有两种情况
//  会让文件停在"一半改了、一半没改"的状态：
//
//    1. 一条语句跑到一半失败。`UPDATE t SET x = 'abc'` 改到第 3 行
//       才碰上类型不匹配——前 2 行已经改了，而且下一次写回
//       会把它们一起带出去。
//    2. 进程在写回的过程中没了（掉电、被 kill、蓝屏）。
//
//  两种情况的解法是同一个：**改之前先把"原来的样子"记下来。**
//  出事就照着记录退回去。这份记录就是回滚日志。
//
//  ------------------------------------------------------------
//  文件长什么样
//  ------------------------------------------------------------
//
//      +--------------------------------------+
//      | 32 字节的日志头                       |
//      |   0  5  magic "ACORJ"                |
//      |   5  1  格式版本                     |
//      |   6  2  保留                         |
//      |   8  4  事务开始时库文件有几页        |
//      |  12  4  头这 12 个字节的校验和        |
//      |  16 16  保留                         |
//      +--------------------------------------+
//      | 记录 0: 4 字节页号 + 4096 字节原始内容 |
//      | 记录 1: 同上                          |
//      | ...                                   |
//      +--------------------------------------+
//
//  【为什么头里要存"事务开始时库文件有几页"】
//  因为事务可能**让文件变长**——插数据要新页。回滚时那些新页
//  得整个切掉，不然它们会永远留在文件里没人管（空闲链上也没有）。
//  切到几页？就是事务开始时的页数。而这个数只有日志知道：
//  页数是从文件大小算出来的，一旦文件长了，原值就没了。
//
//  【为什么头里有一个校验和】
//  因为"日志文件存在"不等于"日志写完整了"。写到一半掉电，
//  头可能是半截的——而半截的头里那个"几页"是**任意一个数**，
//  照着它切会把库文件切坏。
//
//  所以校验和对不上就不认这个头，报错、不动库文件。
//  这是这一层唯一一处"宁可不修，也不能猜"的地方：
//  猜错的代价是**把本来还好的数据改坏**，比不修严重得多。
//  （校验和就是把头那 12 个字节加起来。它不需要防篡改，
//   只需要判断"这是不是一个完整的头"。）
//
//  【为什么每条记录只记页号，不记"这一页在文件里的偏移"】
//  因为偏移就是 `页号 × 4096`，能算出来的东西不存。
//  （和 page.hpp 里"文件头不存页数"是同一条原则。）
//
//  ------------------------------------------------------------
//  日志在什么时候必须落盘
//  ------------------------------------------------------------
//
//  ★ 这条不变式是整个阶段 5 的命根子 ★
//
//    **某一页的新内容写进库文件之前，它的旧内容必须已经在日志里。**
//
//  顺序反了的话：库文件已经改成新的了，日志里却没有旧的，
//  这时候崩溃就再也退不回去了——那才是真正的数据损坏。
//
//  所以每一次往库文件写页（提交时的批量写、缓存淘汰时的单页写）
//  之前都要 syncIfNeeded()。这个"刷"不是"写到文件里"，
//  是**真的交给磁盘**（Windows 上是 _commit，POSIX 上是 fsync）——
//  只交给操作系统的话，掉电时它也可能还在内存里躺着。
//
//  这是"为什么数据库需要 fsync"最具体的一个例子：
//  不是因为怕丢数据，是因为**顺序**。两次写之间没有这道闸门，
//  顺序就是操作系统说了算，而它不知道哪一次更重要。
// ============================================================

#include <cstdint>
#include <cstdio>
#include <functional>
#include <string>
#include <unordered_set>
#include <vector>

#include "page.hpp"

// "把文件描述符上的东西真正交给磁盘"和"把文件截短"这两件事，
// 标准 C++ 里没有（C++17 的 <filesystem> 能截短，但它要的是一个
// 路径，而这两个地方手里都已经有一个打开着的文件了——先关掉再
// 按路径截，中间那一小段窗口正好是出事的窗口）。
// 所以只能用平台自己的那两个：
//
//     Windows:  _commit / _chsize    （<io.h>）
//     POSIX:    fsync  / ftruncate   （<unistd.h>）
//
// 放在这个头文件里，是因为它是这一阶段引入的概念，
// 而 journal.cpp 和 pager.cpp 两边都要用。
#ifdef _WIN32
#include <io.h>
#else
#include <unistd.h>
#endif

// 日志文件的位置：库文件旁边，名字后面加 "-journal"。
// （SQLite 用的是同一个后缀，理由也一样：它必须和库文件绑在一起，
//   用户挪库文件的时候日志得跟着走，不然下次打开会认不出它。）
std::string journalPathFor(const std::string& dbPath);

// 日志文件现在在不在磁盘上。
//
// 【为什么单独一个函数，而不是去问 Journal 对象】因为
// Pager 需要在**构造 Journal 之外**的时刻问这句话：开库的时候
// 要先判断"有没有日志要恢复"，才知道该拿共享锁还是独占锁。
// 那时候手里还没有一个"打开着的日志"——它可能压根不存在。
bool journalFileExists(const std::string& dbPath);

// 把一个已经写下去的 std::FILE* 真正交给磁盘（Windows 上是 _commit，
// POSIX 上是 fsync）。
//
// 【为什么不叫 flush】因为 std::fflush 只是把 C 库的缓冲区交给
// **操作系统**，操作系统自己还有一层页缓存，掉电时那一层也会丢。
// 这两件事经常被混为一谈，而它们的区别正是这一阶段最要紧的那条：
// 我们需要的不是"数据进了文件"，是"数据已经不在内存里了"。
//
// 它住在 journal.hpp 里只是因为这一阶段是它第一次被需要，
// 而日志是最需要它的地方（见上面那段"日志在什么时候必须落盘"）。
// Pager 也用同一个——两处都自己写一遍的话，
// 早晚会有一处只写了 fflush，而那一处不会报错，只会悄悄地不够稳。
void syncFileToDisk(std::FILE* file);

// 日志头的字节数。记录从它后面开始。
constexpr size_t JOURNAL_HEADER_SIZE = 32;

// 一条记录 = 4 字节页号 + 一整页原始内容。
constexpr size_t JOURNAL_RECORD_SIZE = 4 + PAGE_SIZE;

class Journal {
public:
    // dbPath 为空 = 内存库。内存库没有崩溃恢复这回事（进程一退全没），
    // 但 **ROLLBACK 和"一条语句要么全做要么全不做"照样要有**——
    // 所以内存库也要记日志，只是记在内存里，不落文件。
    // （和 Pager 的 memory_ 是同一个套路：换一个落点，逻辑一份。）
    explicit Journal(const std::string& dbPath);
    ~Journal();

    Journal(const Journal&) = delete;
    Journal& operator=(const Journal&) = delete;

    // 开一个事务。pageCount 是库文件**现在**有几页。
    void begin(uint32_t pageCount);

    // 记一页"原来长什么样"。
    //
    // 【同一页只记第一次】后面再调是空操作。这一点是必须的：
    // 事务里同一页会被改很多次（插一行、再插一行……），
    // 而回滚要的是**最开始**那个样子。要是每次都记，
    // 回滚时按顺序重放，最后落地的是倒数第二次的中间状态——
    // 看着像"退了一半"，比不退还难查。
    //
    // 【调用方有责任保证这一页还没被改过】这里拦不住：
    // 传进来的是个 char*，我们没法知道它是不是已经脏了。
    // 所以 Pager 把"取一页准备改"做成了一个独立的入口
    //（getForWrite），并在 markDirty 那里放了一道检查。
    void record(uint32_t pageNo, const char* page);

    // 这一页在这个事务里记过了吗。
    // Pager::markDirty 用它做那道检查。
    bool has(uint32_t pageNo) const { return seen_.count(pageNo) != 0; }

    size_t recordCount() const { return pageNos_.size(); }

    // 把日志刷到磁盘。**往库文件写任何一页之前都必须先调它。**
    // 没有新记录时是空操作（所以可以放心地在热路径上每次调）。
    void syncIfNeeded();

    // 事务结束了（提交完或者回滚完）：删掉日志文件，状态归零。
    //
    // ★ 这一步就是"提交"本身 ★
    // 提交没有别的动作——把页写进库文件只是"准备工作"，
    // 只有删掉日志才让它变成既成事实。因为崩溃恢复的判据是
    // "日志还在不在"：在就说这个事务没做完，退回重来。
    // 所以哪怕所有页都写完了，只要日志还在，下次打开还是会退回去。
    void forget();

    // 回滚时用：把记下来的每一页交给 fn(页号, 原始内容)。
    // **这里只负责"交出来"**，怎么落到库文件上是 Pager 的事——
    // 日志不该知道库文件是文件还是内存。边界划在这儿，
    // 这一层就完全不需要区分两种库（见 Pager::rollbackTransaction）。
    void forEachRecord(const std::function<void(uint32_t, const char*)>& fn) const;

    uint32_t originalPageCount() const { return originalPageCount_; }

    bool active() const { return active_; }

    // 日志文件真的存在于磁盘上吗。
    // （active() 是"事务开着"，和这个是两回事：事务开着但一页都没改过时，
    //   日志文件根本还没建出来——SELECT 用不着日志。）
    bool fileExists() const;

private:
    // 两种落点（文件 / 内存）下面共用的两个动作。
    // 理由和 Pager::readFromDisk / writeToDisk 一样：
    // 除了这两个函数，别处完全不用区分。
    void writeAt(size_t offset, const char* data, size_t length);
    void readAt(size_t offset, char* out, size_t length) const;

    // 第一次 record 的时候才建文件、写头。
    // 【为什么不是 begin 的时候就建】因为绝大多数语句根本不改数据
    //（SELECT 是绝大多数）。每敲一条 SELECT 就建一个文件再删掉，
    // 白白两次系统调用。等真要记了再建，一次都不多花。
    void openIfNeeded();

    std::string path_;      // 空 = 内存库
    std::FILE* file_ = nullptr;
    std::vector<char> memory_;  // 内存库的"日志文件"

    std::vector<uint32_t> pageNos_;   // 记过的页号，按记录顺序
    std::unordered_set<uint32_t> seen_;

    uint32_t originalPageCount_ = 0;
    bool active_ = false;
    bool opened_ = false;
    bool needsSync_ = false;
};

// 打开库之前调一次：如果上次没走完（日志文件还在），先把库文件退回去。
//
// 【为什么要"退回去"而不是"接着做完"】
// 因为回滚日志里只有**旧**内容。我们没法把没提交的事务"做完"——
// 那些改动只存在于崩溃前的内存里，磁盘上没有。所以唯一的选择是退回。
// （能"接着做完"的是重做日志（redo log），那是另一个设计。
//   两种日志都能保证原子性，区别是崩溃后往哪个方向走。）
//
// 做完之后日志文件会被删掉。返回 true 表示确实退了一次。
// 日志头读不出来时抛 AcornError（宁可不修，也不能猜）。
bool recoverJournal(const std::string& dbPath);
