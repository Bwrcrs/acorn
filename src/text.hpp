#pragma once

// ============================================================
//  text —— 跟"文本在终端里占多宽"有关的小工具
//
//  为什么需要单独一个文件：**中文在终端里占两格，ASCII 占一格**。
//  而内存里一个中文字符占 3 个字节。这三个数字（字符数、字节数、
//  显示宽度）全都不一样，混淆任意两个都会出问题：
//
//    · 按字节数决定"字符串多长" → 中文串看起来会长一倍
//    · 按字符数决定"占几格"    → 表格里带中文的那一列会错位
//
//  数据库的输出里出现中文是常事（中文表名、中文数据），
//  所以这张对齐的账必须算对。
//
//  有两个地方要用它，这也是它必须只有一份实现的原因：
//    · 报错时把箭头指到正确的列（error.cpp）
//    · 打印结果表格时把每列对齐（main.cpp）
//
//  【这是个近似】判断依据是"UTF-8 里 3 字节及以上的码点算两格"。
//  严格的实现要查 Unicode 的 East Asian Width 表，因为有些 3 字节
//  字符（部分标点、部分符号）其实只占一格。
//  对本项目够用，但要知道它是个近似——真实终端里偶尔会差一格。
// ============================================================

#include <cstddef>
#include <string>

// 从头数 charCount 个**字符**（不是字节），折算成终端显示宽度。
int displayWidth(const std::string& text, size_t charCount);

// 整个字符串占几格。
int displayWidth(const std::string& text);

// 右边补空格补到 width 格宽。本来就有这么宽（或更宽）就原样返回。
//
// 注意补的空格数是按"显示宽度"算的，不是按字符数——
// 这正是不能直接用 std::string 的 resize 或者 printf 的 %-10s 的原因：
// 那两样都是按字节/字符算的，碰上中文就会少补或多补。
std::string padRight(const std::string& text, int width);
