#pragma once

#include <cstdio>
#include <string>

// ============================================================
//  路径（阶段 6 补的）
//
//  Acorn 内部一律用 UTF-8 存字符串：SQL 里的中文、报错里的表名、
//  库文件的名字，全是 UTF-8。这在 Windows 上有个坑，而且这个坑
//  不报"我不认识这个字"，它报别的东西。
//
//  C 标准库的 fopen / remove / std::ifstream 收的是**窄字符**，
//  而 Windows 的窄字符文件 API 走的是**系统 ANSI 代码页**
//  （这台机器上是 GBK）。把 UTF-8 的「测试库.db」交给 fopen，
//  它不会拒绝，它会拿 GBK 去解释这串字节——于是去找一个名字
//  完全不同的文件。后果有两种，一种比一种难查：
//
//    · 报错说"目录不存在？"，可目录明明在。为什么会这样：
//      UTF-8 里一个汉字三字节，GBK 一个汉字两字节，所以解码
//      会错位；错位之后只要有一个字节是 0x5C，它就成了反斜杠，
//      路径被切成别的目录。（实测：`-d 测试库.db` 报的就是
//      "建不了数据库文件：测试库.db（目录不存在？没有写权限？）"，
//      而那个目录里当时只有孤零零一个 测试库.db-lock。）
//
//    · 更坏的情况：GBK 恰好拼出一个合法名字，于是**悄悄建出
//      另一个文件**，程序一切正常。用户下次拿自己的名字去开，
//      发现数据没了——而且没有任何一步报过错。
//
//  所以凡是碰路径的地方都得走这一层：Windows 上先转成宽字符，
//  再调宽字符版本（_wfopen / _wremove）；别的平台直接调。
//
//  【为什么锁那一层不需要它】因为锁定那一层一开始就是用
//  CreateFileW 写的（宽字符 API）。也正是它把这件事暴露出来的：
//  库文件建不出来的时候，锁文件 测试库.db-lock 却好好地建了出来。
// ============================================================

// 打开一个路径。mode 的写法和 fopen 一样（"rb" / "w+b" / ...）。
// 打不开时返回 nullptr——调用方负责报错，因为只有它知道
// "打不开"在这个上下文里是什么意思。
std::FILE* openPath(const std::string& path, const char* mode);

// 删掉一个路径。删不掉返回非 0。
int removePath(const std::string& path);

#ifdef _WIN32
// UTF-8 转宽字符。给那些不经过上面两个函数、自己就要调宽字符
// API 的地方用（比如 CreateFileW）。转不动时返回空串。
std::wstring utf8ToWide(const std::string& text);
#endif
