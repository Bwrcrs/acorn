#pragma once

// ============================================================
//  Btree —— 阶段 4 的 B+ 树
//
//  ★ 这个文件回答的是"怎么不把整张表读一遍就找到一行" ★
//
//  ------------------------------------------------------------
//  它要解决的问题
//  ------------------------------------------------------------
//
//  阶段 3 的表是一串用 next 串起来的数据页（见 table.hpp 那张图）。
//  要 `SELECT * FROM users WHERE id = 500`，只能从第一页开始走，
//  一页一页读，一行一行比。这叫全表扫描，代价 O(行数)。
//
//  行数少的时候无所谓。10 万行、每行 100 字节 = 10MB = 2500 页，
//  查一行要把 2500 页全读一遍——而其中有用的只有 1 页。
//  索引要做的就是把"读 2500 页"变成"读 3、4 页"。
//
//  ------------------------------------------------------------
//  为什么是 B+ 树，不是哈希表、也不是二叉搜索树
//  ------------------------------------------------------------
//
//  · **哈希表**能 O(1) 找到"等于某个值"，但 `WHERE id > 100` 这种
//    范围查询完全帮不上忙——哈希把顺序彻底打散了。
//    而且哈希表要预判桶的数量，数据长大了得整体重建。
//
//  · **二叉搜索树**（包括红黑树）每次比较都要往下走一层。
//    100 万条数据，树高约 20 层。在内存里 20 次跳转没问题，
//    但在磁盘上**每一层都是一次随机读**——20 次磁盘寻道，
//    几毫秒一次，就是几十毫秒。
//
//  · **B+ 树**把"一层"变宽了：一个 4KB 的节点能放几百个键，
//    于是 100 万条数据树高只有 3~4 层。查一行 = 3~4 次磁盘读，
//    而且最上面那两层基本总在缓存里，实际上只有最后一次真读盘。
//
//    这就是 B+ 树的全部要义：**让树变矮，因为磁盘 IO 的次数
//    等于树的高度**。它不是"更快的二分查找"，它是"为磁盘设计的
//    二分查找"。（如果数据全在内存里，二叉树的层数根本不是问题，
//    所以内存数据库用红黑树 / SkipList 的反而更多。）
//
//  ------------------------------------------------------------
//  它长什么样
//  ------------------------------------------------------------
//
//              [ 内部节点 ]
//              |     |     |
//      +-------+     |     +-------+
//      v             v             v
//   [叶子] <---> [叶子] <---> [叶子] <---> 没有了
//    键->行        键->行        键->行
//
//  · **叶子**存的是 (键, RowId)——"这个值在哪一行"。叶子之间用
//    页头的 next 串成一条链，这是范围查询能高效的原因：
//    找到起点之后顺着链往下读就行，不用回到树上去。
//  · **内部节点**存的是 (键, 子页号)——"比这个键小的往这边走"。
//    它**不存数据**，只存路标。所以在内部节点里找不到某一行，
//    只能找到"那一行大概在哪棵子树里"。
//  · **数据只在叶子里**，而且内部节点里的键是**拷下来的副本**
//    （不是搬上来的）。这和多数的二叉搜索树不一样——B 树的键在
//    整棵树里只出现一次，B+ 树的键内部节点里也有一份。
//    代价是浪费一点空间，换来的是"所有行都在同一层，
//    找哪一行都是同样的代价"，不用管"这个值恰好停在内部节点上"。
//
//  ------------------------------------------------------------
//  ★ 键其实是 (列的值, 行号) 两截拼起来的 ★
//  ------------------------------------------------------------
//
//  这是整个文件里最容易漏掉、漏掉之后最难查的一件事。
//
//  一列上是允许有重复值的（`CREATE TABLE t (id INT)` 之后，
//  你可以插一百行 id 都是 5）。B+ 树的"路标"（内部节点里的键）
//  在这种情况下会指向一个**含糊的位置**：
//
//      叶子A: [5, 5, 5]      叶子B: [5, 5, 5, 6]
//      父节点: [5 -> A] [5 -> B]
//
//  现在要找"所有的 5"。从根往下：父节点的两个路标都是 5，
//  按"最后一个 <= 5 的路标"这个规则，会走到 B——
//  于是 A 里的三个 5 **永远找不到了**。查出来 3 行，实际有 6 行。
//
//  【解法：让键唯一】把 RowId 拼在列值后面，作为真正的键。
//  行号是行的身份证，同一个键不可能有两行——于是树里的键**唯一**，
//  "路标指向哪个孩子"就不再含糊了。
//
//      叶子A: [(5,p1), (5,p3), (5,p7)]    叶子B: [(5,p9), (5,p11), (6,p2)]
//      父节点: [(5,p9) -> B]   ← 清清楚楚
//
//  这个做法是跟真数据库学的：SQLite 的索引条目是
//  (列值..., RowId)，PostgreSQL 的 btree 索引条目也是
//  (列值..., TID)。**不是因为我们想存行号**（叶子本来就要存），
//  而是因为**唯一的键才能让路标有意义**。
//
//  【代价】内部节点里也要多存 6 个字节的行号。这些行号
//  在内部节点里**从来不被解引用**，只参与比较——纯属为了让
//  比较有确定结果而付的钱。
//
//  ------------------------------------------------------------
//  和 page.hpp / pager.hpp 的分工
//  ------------------------------------------------------------
//
//  btree 只管"树怎么长"：往哪个孩子走、什么时候分裂、键怎么比。
//  它不碰文件（那是 pager 的事），也不管一个页里第几个字节是什么
//  （那是 page 的事）——它用的是和表一样的槽位页，只是页类型是
//  BTREE_LEAF / BTREE_INTERNAL。所以 heapInsertAt / heapCell /
//  heapDelete / heapCompact 这些全是**同一份实现**，
//  B+ 树这边一行页内布局的代码都不用写。
//
//  ★ 这一层里唯一"和磁盘有关"的知识是：**页的大小是有限的**，
//    所以节点会满、会分裂。把这一条换掉（比如假设空间无限），
//    整棵树的代码会塌缩成"往一个有序数组里插"。
//
//  ------------------------------------------------------------
//  ★ 删除为什么不合并节点 ★
//  ------------------------------------------------------------
//
//  教科书上的 B+ 树删除要做两件事：从叶子里删掉条目，然后
//  如果节点太空了就"借一个"或者"和兄弟合并"。本文件**只做第一件**。
//
//  理由是那条路标规则（"最后一个 <= 要找的键的路标"）有一个
//  很好的性质：**路标过期了也依然是对的**。一个路标原来是某棵
//  子树里最小的键，后来那个键被删了——路标变得比子树里实际的
//  最小键还小。但这不影响它当路标用：
//
//    · 子树里的键只会变大（不会突然冒出比路标还小的键，
//      因为比路标小的键会被路由到左边那个孩子去）
//    · 所以"比路标小的往左走、比路标大的往右走"这条分工一直成立
//
//  合并和借位是为了**省空间**，不是为了**正确性**。省下来的
//  是一棵几乎空的树里的几个页；换来的是插入路径和删除路径上
//  各一大段对称的代码，以及"删除时要往上走一遍"这件事。
//  这一版不写，所以：**删空的叶子页留在原地**（它还是链上的一环，
//  只是没有条目了），文件不会因为删除而变小。这跟阶段 3
//  "文件只长不缩"是同一笔账，写进 README 的已知问题里。
// ============================================================

#include <cstdint>
#include <functional>
#include <string>
#include <vector>

#include "page.hpp"
#include "pager.hpp"
#include "value.hpp"

// 内部节点第 0 个条目的"键"标签。
//
// 第 0 个条目指向最左边那个孩子，它"比所有键都小"，没有下界，
// 所以这一格没有键，只有一个子页号。用一个单独的标签占位，
// 而不是给结构加个特例字段——这样每个条目**形状一样**，
// 找孩子、比较、分裂这些循环都能统一写，不用满处判断"是不是第 0 个"。
//
// 【为什么是 0x05】page.hpp 里的值标签用了 0x00~0x04，
// 05 是空的，而且它**不会**被 decodeValue 认出来——
// 认不出来的标签 decodeValue 会直接报"文件坏了"。
// 这正是我们要的：这个标签只出现在内部节点的第 0 个位置，
// 出现在别的地方就是文件真的坏了。
constexpr unsigned char BTREE_NO_KEY = 0x05;

// 索引的键最长能有多少字节（**编码之后**）。
//
// 取的是**内部节点条目**的上限：内部条目比叶子条目多 4 个字节的
// 子页号，所以它先撞墙。一个键要两边都能放下，才算"永远放得下"。
// 调用方（Database）在插入之前查这个，为的是能把
// "这个键太大"和"这一页满了"区分开——后者重试就好，前者永远好不了。
constexpr size_t MAX_KEY_BYTES = MAX_CELL_SIZE - 10;

// 索引里能放的键对应的**文本**长度上限（给报错信息用）。
// 编码会比原文多 5 个字节（1 字节标签 + 4 字节长度）。
constexpr size_t MAX_INDEX_TEXT = MAX_KEY_BYTES - 5;

class Btree {
public:
    // rootPage 是根节点在哪一页。这个数**会变**——树长高一层时
    // 会有一个新的根，那时候调用方要把它存回目录记录里
    //（见 Btree::rootPage 和 Database::insertRow 里那一段）。
    //
    // keyType 是这一列的类型，只用来做一致性检查（比如"往整数
    // 索引里插文本"这种内部错误，希望当场就炸而不是悄悄写进去）。
    Btree(Pager& pager, uint32_t rootPage, Value::Type keyType);

    // 根页号。和构造时传进来的可能不一样了。
    uint32_t rootPage() const { return rootPage_; }

    // 插一条 (键 -> 行)。键可以重复（SQL 里没有 UNIQUE 约束的话，
    // 两行的 id 就是可以一样的），重复的键按行号排队。
    //
    // 键太长时抛 AcornError——这不是"这一页满了"，是"这个键
    // 永远装不进任何一页"，重试多少次都没用。
    void insert(const Value& key, RowId id);

    // 删掉"键是 key、行是 id"的那一条。找到删掉返回 true，
    // 没找到返回 false（**不抛异常**：索引里没有这一条，
    // 和"索引坏了"是两件事，调用方得能区分）。
    //
    // 【注意它删的是"哪一条"，不是"哪些条"】
    // 键相同的可能有好几条（好几行的这一列都是 5），所以必须
    // 连 RowId 一起比才能确定删对人了。少了这个，
    // `DELETE FROM t WHERE id = 1` 可能会把 id = 2 那行的索引项删掉。
    bool remove(const Value& key, RowId id);

    // 等值查找：把所有"键等于 key"的行的 RowId 交给 visit。
    void searchEqual(const Value& key,
                     const std::function<void(RowId)>& visit) const;

    // 范围查找。hasLower / hasUpper 为 false 表示那一头没限制。
    // 边界含不含（`>` 还是 `>=`）由 inclusive 决定。
    //
    // 【这是 B+ 树相对哈希表的核心优势】
    // `WHERE id > 100`、`WHERE id < 50`、`BETWEEN 10 AND 20`
    // 全都能用它。哈希索引这些一个都做不了。
    void searchRange(bool hasLower, const Value& lower, bool lowerInclusive,
                     bool hasUpper, const Value& upper, bool upperInclusive,
                     const std::function<void(RowId)>& visit) const;

    // 从最左边开始走一遍所有叶子，按顺序交出所有 RowId。
    // 现在没人用它（全表扫比它快——不用一行一行回表读数据），
    // 但它是"这棵树是不是好的"最直接的检查手段。
    void scanAll(const std::function<void(RowId)>& visit) const;

    // 这棵树占的所有页，**按从根往下、从左往右**的顺序。
    // DROP INDEX 用它来把页还给空闲链。
    std::vector<uint32_t> allPages() const;

private:
    // 一次分裂的结果：多出来一个新节点，父节点要记住
    // "从 sepKey 这个键开始往新节点走"。
    //
    // sepKey 是**键部分的字节**（键的编码 + 6 字节行号），
    // 不是 Value。因为父节点要的是一段能直接拼成条目的字节，
    // 拆成 Value + RowId 再拼回去，中间那两步纯属白干。
    struct Split {
        bool happened = false;
        uint32_t newPage = INVALID_PAGE;
        std::string sepKey;
    };

    // 往以 pageNo 为根的子树里插一条条目，返回有没有分裂。
    Split insertInto(uint32_t pageNo, const std::string& entry,
                     const Value& key, const RowId& id, int depth);

    // 分裂。entries 是"分裂之后应该有的全部条目"（含新插的那一条），
    // 函数负责决定从哪切开、写两个页、返回分隔键。
    // next 是老页的 next（叶子要保住那条链）。
    Split splitNode(uint32_t pageNo, PageType type,
                    const std::vector<std::string>& entries, uint32_t next);

    // 从根走到 key 应该在的那个叶子的页号。
    uint32_t descendToLeaf(const Value& key, const RowId& id) const;
    uint32_t leftmostLeaf() const;

    // 新条目该插在活着的条目里的第几个位置。
    //
    // 【返回的是"活着的第几个"，不是"第几个槽位"——这两个数不一样】
    // 叶子上删过东西之后会留下墓碑，而 readEntries 是跳过墓碑的，
    // 所以 vector 里只有活着的条目。要是这里返回槽号，
    // 有墓碑的时候两个下标就对不上，新条目会插错位置——
    // 而"插错位置"在 B+ 树里的后果是**顺序坏了**，
    // 表现是有的行查得到、有的查不到。
    uint16_t insertPosition(const char* page, const Value& key,
                            const RowId& id) const;

    // 在一页里找"该走哪个孩子"。返回该走的孩子在第几个条目上。
    // 【规则：最后一个分隔键 <= (key,id) 的条目】见文件头的说明。
    uint16_t chooseChild(const char* page, const Value& key,
                         const RowId& id) const;

    // 把一个节点页的所有条目**按顺序**读出来（跳过墓碑）。
    //
    // 【为什么返回拷贝而不是指针】因为调用方拿到之后要往中间插一条、
    // 还要递归下去——递归会取别的页，当前这一页有可能被踢出缓存，
    // 那时候原来的指针就指向别人的数据了。
    // 拷贝几百个短字符串换掉这个隐患，值。
    std::vector<std::string> readEntries(const char* page) const;

    // 用给定的条目重建一个节点页（内容和顺序完全照抄）。
    // 分裂和"插进去之后重排"都用它——比"在原地插一条、挪字节、
    // 处理放不下"简单得多，而且重建完不留墓碑。
    void rebuild(char* page, PageType type, uint32_t next,
                 const std::vector<std::string>& entries) const;

    // 从 startLeaf 开始顺着叶子链扫，按范围过滤。
    void scanFrom(uint32_t startLeaf, bool hasLower, const Value& lower,
                  bool lowerInclusive, bool hasUpper, const Value& upper,
                  bool upperInclusive,
                  const std::function<void(RowId)>& visit) const;

    void collectPages(uint32_t pageNo, std::vector<uint32_t>& out,
                      int depth) const;

    Pager* pager_;
    uint32_t rootPage_;
    Value::Type keyType_;

    // 递归深度上限。树高是 O(log n)，正常永远到不了；
    // 这是给"文件被改坏了、某个内部节点指向了自己"兜底的——
    // 那时候宁可报错，也不要卡死在死循环里。
    static constexpr int MAX_DEPTH = 32;
};
