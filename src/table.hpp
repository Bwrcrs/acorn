#pragma once

// ============================================================
//  Table —— 一张表的数据（阶段 3：搬到磁盘上了）
//
//  ★ 这个文件是"留缝到底值不值"的答案 ★
//
//  阶段 1 的时候，这个文件的头文件里写着一段话，大意是：
//  scan() 收回调而不是返回 vector，是为了阶段 3 换磁盘存储时
//  执行器那一层一个字都不用改。
//
//  现在阶段 3 真的到了。**执行器确实一个字都没改**——
//  它看到的仍然是 `table.scan([](RowId id, const Row& row){...})`，
//  仍然拿着 RowId 当不透明句柄传来传去。
//
//  但也要把话说全：留缝省掉的是**调用方**的改动，
//  不是全部的改动。这个文件本身从 100 行变成了 200 行，
//  行不再住在 vector 里，而是住在 4KB 的页里。
//  留缝的价值在于"改动被关在一个地方"，不是"没有改动"。
//
//  ------------------------------------------------------------
//  一张表在磁盘上长什么样
//  ------------------------------------------------------------
//
//   目录记录（存在目录页里）
//        |
//        | 记着这张表的第一个数据页
//        v
//   +---------+    +---------+    +---------+
//   | 数据页 3 | -> | 数据页 7 | -> | 数据页 9 | -> 没有了
//   +---------+    +---------+    +---------+
//
//  数据页之间用页头里的 next 串成一条单链表。
//  每个数据页内部是槽位页（见 page.hpp 的图）：槽位数组 + cell 区，
//  一个 cell 就是一行编码之后的字节。
//
//  【为什么用链表，不用"一整块连续的空间"】
//  因为表会长大。连续空间长大时如果后面那块被别的表占了，
//  就得把整张表搬到别处——搬的时候还要保证中途断电不出事。
//  链表没有这个问题：页可以散落在文件的任何地方，加一页就是
//  在链尾挂一页。代价是"第 1000 行在哪"没法算，只能从头走——
//  这正是阶段 4 的 B+ 树要解决的（它让查找不用从头走）。
// ============================================================

#include <cstddef>
#include <cstdint>
#include <functional>
#include <vector>

#include "page.hpp"
#include "pager.hpp"
#include "schema.hpp"
#include "value.hpp"

class Table {
public:
    // firstPage 是这张表的第一个数据页。建表时由 Database 分配好，
    // 打开时从目录记录里读出来。
    //
    // 【为什么打开表的时候不顺便数一遍行数】
    // 数一遍要把所有页读一遍——库大的时候光打开就要好几秒。
    // 而且数出来的行数马上就会过期。需要的行数都是当场数
    //（SELECT COUNT(*) 就是扫一遍），所以不缓存。
    Table(Pager& pager, TableSchema schema, uint32_t firstPage);

    const TableSchema& schema() const { return schema_; }
    uint32_t firstPage() const { return firstPage_; }

    // 插入一行，返回它落在哪。会检查列数和每列的类型，不合规抛 AcornError。
    //
    // 【为什么校验放在这里，而不是执行器里】
    // "表里每一行都符合表结构"这条不变式，应该由**拥有这些行的人**来守。
    // 放在执行器里的话，将来任何一个新的插入路径（导入文件、
    // 从别的表复制、以后加事务回滚重放）都得自己记得校验一遍，
    // 漏一个就能把脏数据写进去。
    // 放在这里，就只有这一个入口，绕不过去。
    //
    // 【为什么 row 是引用，而且返回值是行号（阶段 4 才变成这样）】
    // 两件事都是被索引逼出来的，而且都是同一件事：**调用方需要
    // 看到"真正存进去的那一行"和"它落在哪"**。
    //   · 列是 REAL 的时候，校验会把整数 3 就地补成浮点 3.0。
    //     索引里该存的是补完之后那个值。传值的话，调用方手里
    //     还是那个整数——它和 3.0 比较时相等，所以查得到，
    //     但"索引里存的和行里存的不一样"本身就是个隐患。
    //   · 索引里存行号。这一行落在哪，只有插完才知道。
    RowId insert(Row& row);

    // 全表扫描：把每一行连着它的 RowId 依次交给 visit。
    void scan(const std::function<void(RowId, const Row&)>& visit) const;

    // 按行号取出一行。
    //
    // 【这一步叫"回表"，阶段 4 才第一次需要它】
    // 索引里存的是行号，不是行本身。顺着 B+ 树找到行号之后，
    // 还得回到表的数据页里把那一行读出来——这就是回表。
    //
    // 索引里为什么不直接存整行（那样就不用回表了，叫"覆盖索引"）：
    // 一行的字节可能比键大几十倍，存进树里树会胖得没法看，
    // 而树的胖瘦直接决定树高，树高就是磁盘读的次数。
    // （真数据库两种都做：默认回表，需要的时候显式建覆盖索引。）
    //
    // 行号指向空位就抛 AcornError——**不能悄悄跳过**。
    // 那种情况说明索引和表已经对不上了（该删的没删掉），
    // 跳过的话查询会静悄悄地少返回几行，正好是最难查的一类 bug。
    Row row(RowId id) const;

    // 改一行，返回这一行**现在**的行号。
    //
    // 【返回值是阶段 4 加的，因为 RowId 真的会失效】
    // 改的时候优先原地改（新值不比旧值长的话，字节位置都不动），
    // 槽位下标不变，行号就不变。整页都塞不下时，这一行会挪到
    // 别的页去，老行号从此指向一个墓碑——这时候返回的是新行号。
    //
    // 阶段 2/3 那个 void 返回值是靠"执行器改完就不再看了"这条
    // 口头约定撑着的（见 table.hpp 的历史）。现在索引里也存着
    // 行号了，那条约定管不到索引——所以把新行号**返回**出来，
    // 让调用方没法装作不知道。
    //
    // （真数据库在这条岔路上有三种走法：PostgreSQL 的 HOT 更新
    //   干脆不许搬（索引指过去，靠一条链找到新位置）；
    //   InnoDB 是彻底搬、然后在索引里更新指针；
    //   我们选了最直白的一种：搬完了把新行号告诉你。）
    //
    // row 是引用，理由和 insert 一样：校验会就地补型，
    // 调用方（Database）要拿补完型的那一行去更新索引。
    RowId updateRow(RowId id, Row& row);

    // 删一批行。每条 id 指向的槽位变成墓碑。
    //
    // 【阶段 2 那条"必须升序"的要求没了】
    // 阶段 2 的实现是从后往前 erase，所以非要升序不可。
    // 那是**实现细节泄漏到了接口上**——调用方被迫遵守一条
    // 它根本没理由知道的规则。
    // 现在删除只是改一个长度字段，删第 3 行不影响第 5 行，
    // 顺序随便。约束消失得干干净净，因为它的成因消失了。
    void deleteRows(const std::vector<RowId>& ids);

    // 把这张表占的所有数据页还给空闲链。DROP TABLE 用。
    //
    // 【为什么不能边扫边释放】释放一页会改它的页头（写"下一个
    // 空闲页"），而链表的 next 也在页头里——等于走的路上
    // 把路标擦了。所以必须先收集齐页号，再统一释放。
    // （和 DELETE 不能边扫边删是同一类问题，但成因不同：
    //   那边是迭代器失效，这边是**数据本身被改掉**。）
    void releaseAllPages();

private:
    // 最后一个数据页。插入时优先试它。
    //
    // 【为什么是 mutable，而且是懒的】
    // scan() 是 const 的，但它也要走这条链。而"链尾在哪"是
    // 可以从链上问出来的东西——算出来存起来，属于缓存，
    // 不算修改表的逻辑状态（和 std::string 的 length() 一样）。
    // 懒的算，是因为多数表建完之后只查不改，没必要为它走一遍链。
    //
    // 反过来说也成立：要是这里存的是"这张表有几行"，
    // 那个也 mutable 就不对了——行数是**数据**，不是缓存，
    // 它要是和页里的内容对不上，就是真的坏了。
    mutable uint32_t lastPage_ = INVALID_PAGE;

    uint32_t lastPage() const;

    // 把一行编码后的字节放进这张表的某一页，返回它落在哪。
    // 插入和"更新时放不下只好搬家"共用这一份。
    RowId placeAnywhere(const std::string& cell);

    Pager* pager_;
    TableSchema schema_;
    uint32_t firstPage_;
};
