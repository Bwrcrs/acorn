#pragma once

// ============================================================
//  FileLock —— 库文件上的锁（阶段 6）
//
//  ★ 阶段 6 的核心文件 ★
//
//  【它解决的问题】
//  前面五个阶段里，Acorn 都默认"这个库只有我一个进程在开"。
//  这个假设一直没写下来过，但它到处都在用：缓存里那份数据
//  就是全部真相、提交时把脏页写回去就完了……
//
//  两个进程同时打开同一个库会怎样？谁都不会报错。
//  两个进程各有一份自己的页缓存，各自把各自的改动写回去，
//  后写的那个把先写的那个覆盖掉。**数据就那么没了，而且
//  两边都以为自己的 INSERT 成功了。**
//
//  所以需要一个"现在轮到谁"的东西。这个文件就是它。
//
//  ------------------------------------------------------------
//  为什么用操作系统的文件锁，而不是自己写一个 .lock 文件
//  ------------------------------------------------------------
//
//  最直觉的办法是：想写的时候建一个 xxx.lock 文件，里面写上
//  自己的进程号；要写之前先看看这个文件在不在。
//
//  ★ 这个办法有一个绕不过去的洞：进程没了，文件还在。★
//
//  进程被 kill、掉电、任务管理器里点"结束任务"——它都没机会
//  去删那个文件。于是那个文件变成一个**僵尸锁**：库里明明
//  没人在用，后来的人却谁也进不去。要修就得在下一次启动时
//  判断"那个进程号还活着吗"——而在 Windows 上这件事本身
//  就不可靠（进程号会被系统回收再分配，一个早就死掉的
//  进程号可能已经属于别人了）。判断错了就是两个写者，
//  回到原点，而且这次还多了一层"它看起来是好的"。
//
//  操作系统给的文件锁没有这个问题，因为**放锁这件事是内核做的**：
//  进程一消失（不管是怎么消失的），它持有的所有锁立刻全部释放。
//  没有僵尸锁这回事，也没有"判断进程号"这回事。
//
//  一句话：**"锁必须被释放"这个保证，交给内核比自己做对容易得多。**
//  （SQLite 也是这么做的，它锁的就是库文件本身。）
//
//  ------------------------------------------------------------
//  两种锁
//  ------------------------------------------------------------
//
//      SHARED（共享）      我可以读，别人也能同时读，但谁都不能写
//      EXCLUSIVE（独占）   只有我，读写都行
//
//  一个库同时只能处于这三种状态之一（没有锁 / 若干共享 / 一个独占）：
//
//      读 + 读    可以
//      读 + 写    不行
//      写 + 写    不行
//
//  【为什么读也要锁】因为不锁的话，读就可能读到**写了一半**的东西：
//  那边正在把一个页改成新的，这边刚好读那一页。锁要挡的是这个。
//  代价是"读会挡住写、写会挡住读"——要消掉这个代价得上 MVCC
//  （每个读者看自己的一个快照，谁也不挡谁），那是另一个设计，
//  这一阶段没做。这一点在 README 里说清楚了。
//
//  ------------------------------------------------------------
//  锁文件为什么是单独一个文件，不是库文件本身
//  ------------------------------------------------------------
//
//  一个很自然的误解：**"锁文件存在" = "库被锁着"**。
//  不是的。锁是**内核里**的一条记录，和磁盘上有没有那个文件
//  一点关系都没有。那个文件只是个"地址"——大家拿着同一个路径
//  去问内核"这条记录现在归谁"，锁文件自始至终是空的，一个
//  字节都不写。
//
//  搞明白这一点，下面这几条就都顺了：
//    · 锁文件一直留在磁盘上没关系（我们的就是不删的）。
//      它有 0 个字节，删不删都不影响任何事。
//    · 库文件的字节一个都不碰。这点在 Windows 上特别要紧：
//      那边的字节范围锁是**强制**的，锁在数据页上会让别的进程
//      连 fread 都读不了，锁的范围一旦算错就是一堆莫名其妙的
//      "文件被占用"。
//    · 换一种锁的粒度（比如以后按页加锁）只要换锁文件里的
//      字节范围，数据文件完全不受影响。
//
//  ------------------------------------------------------------
//  什么时候拿、什么时候放
//  ------------------------------------------------------------
//
//  这一层的规矩（Pager 照着执行）：
//
//    打开库            -> 先拿 SHARED（"我要读"）
//    要开一个写事务    -> 升级成 EXCLUSIVE
//    事务提交 / 回滚   -> 退回 SHARED
//    进程退出          -> 内核自动全放掉
//
//  【为什么不等到真要写第一页的时候才升级】因为一次改动里
//  "读"和"写"是混在一起的：`UPDATE t SET x = 1 WHERE y > 5`
//  得先扫一遍表（读），再改行（写）。要是等到写的那一刻才升级，
//  中间那段读就是**没有锁保护的读**——别的进程在此期间提交，
//  我们就是拿着过期数据在做决定（经典的丢失更新）。
//  所以升级的时机是"事务开始"，不是"第一次写"。
//
//  【为什么不做"升级失败就等"之外的事】因为两个都拿着共享锁的
//  进程如果都想升级，就是死锁：谁都不肯先放手，谁都等不到。
//  我们干脆不给自己这个机会——升级就是"放掉共享、去抢独占"，
//  抢不到就**明确报错让用户重试**，绝不在内核里干等。
//  （SQLite 把这个窗口收得更紧一点，用一个 PENDING 状态挡住
//   新读者、等老读者退干净，代价是多一个状态。这里省了。）
// ============================================================

#include <string>

// "没有句柄"这件事在两个平台上长得不一样：
// Windows 的句柄是个 void*（空就是 nullptr），POSIX 的文件描述符
// 是个 int（空是 -1，因为 0 是合法的描述符）。用一个名字把它盖住，
// 下面那些 if 就不用每个都写两遍。
#ifdef _WIN32
using LockHandle = void*;
constexpr LockHandle NO_HANDLE = nullptr;
#else
using LockHandle = int;
constexpr LockHandle NO_HANDLE = -1;
#endif

// 锁文件的位置：库文件旁边，名字后面加 "-lock"。
// （和 journalPathFor 是同一个理由：它必须和库文件绑在一起，
//   用户挪库文件的时候得跟着走。）
std::string lockPathFor(const std::string& dbPath);

enum class LockMode {
    NONE,       // 没拿着
    SHARED,     // 共享：能读，别人也能读，但谁都不能写
    EXCLUSIVE,  // 独占：只有我
};

class FileLock {
public:
    FileLock() = default;
    ~FileLock();

    // 锁是绑在一个打开着的句柄上的，复制一份会让两个对象都以为
    // 自己该去放锁。禁掉，编译器帮我们拦。
    FileLock(const FileLock&) = delete;
    FileLock& operator=(const FileLock&) = delete;

    // 试着拿一把锁。别人占着就返回 false，why 里写一句能看懂的话。
    // dbPath 为空（内存库）时什么都不做，直接返回 true——
    // 内存库别的进程根本看不见，没有"同时用"这回事。
    //
    // waitMs > 0 时会一直重试到拿到锁或者等满了 waitMs 毫秒。
    // 【为什么默认不等待】因为一个"默默地卡住"的程序比一个
    // 报错的程序难查得多。要等是用户明确说出来的（--lock-wait）。
    bool acquire(const std::string& dbPath, LockMode mode, int waitMs,
                 std::string& why);

    // SHARED -> EXCLUSIVE。
    //
    // 【失败时会尽量把共享锁拿回来】这样调用方报完错之后
    // 还能接着读——一个写失败不该让整个进程变成残废。
    // 连共享锁都没拿回来（那一刻正好有别的进程在写），
    // 状态就是 NONE，下次要读的时候会重新去拿（见 ensureSharedLock）。
    //
    // 手里没有共享锁时返回 false（调用方该先 acquire）。
    bool upgrade(int waitMs, std::string& why);

    // EXCLUSIVE -> SHARED。拿不回共享锁就退到 NONE。
    // 【为什么可以失败】因为放掉独占和拿到共享之间有一个缝，
    // 别的进程可能正好挤进来。挤进来的后果只是"我们暂时没锁"，
    // 而不是"我们以为有锁其实没有"——所以是安全的，
    // 只是下一次取页要重新拿一次。
    void downgrade();

    // 全放掉（进程退出时用；内核也会在进程消失时替我们放）。
    void release();

    LockMode mode() const { return mode_; }
    bool held() const { return mode_ != LockMode::NONE; }
    bool exclusive() const { return mode_ == LockMode::EXCLUSIVE; }

private:
    // 锁文件一直开着，两种锁都用这一个句柄。
    // 【为什么不在换锁的时候重新打开】那样"关掉-再打开-上锁"
    // 中间就有一个没锁的缝，而这个缝正好在升级的路径上——
    // 最不该有的地方。
    LockHandle handle_ = NO_HANDLE;

    // 当前锁着的是哪个库。
    // 【为什么要留着】因为报错的时候要说清楚是**哪个文件**被人占着，
    // 而升级失败时调用方手里只有这个对象。
    std::string dbPath_;

    // 现在拿着的是哪种锁。
    LockMode mode_ = LockMode::NONE;
};

