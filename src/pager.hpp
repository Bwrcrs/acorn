#pragma once

// ============================================================
//  Pager —— 页从哪里来
//
//  这一层只回答一个问题：**第 N 页的 4096 个字节在哪**。
//  它不知道页里装的是行还是表结构，也不知道 SQL 是什么。
//
//  【为什么非得有这么一层，直接读文件不行吗】
//  因为"每次读一行就 fseek + fread 一次"会慢到没法用：
//  磁盘的一次随机读是毫秒级的，而内存是纳秒级的，差六个数量级。
//  数据库能跑起来，一半的功劳在**它尽量不碰磁盘**。
//
//  所以中间加一层缓存（buffer pool）：
//    · 读第 N 页 -> 先看缓存里有没有，有就直接给（快）
//    · 没有 -> 从磁盘读一页进来，放缓存，再给
//    · 缓存满了 -> 挑一页踢出去；**脏的**（改过的）先写回磁盘
//
//  这就是数据库里"内存和磁盘之间的那道闸门"。
//  阶段 5 的事务、阶段 6 的并发，都是在**这一层**上继续加东西
//  （日志、锁），所以它值得单独成为一个文件。
//
//  【阶段 6 之后它还多管一件事：这个库现在归谁】
//  因为"页缓存"这件事本身就暗含了"我知道现在数据是什么样"——
//  而这个"知道"只有在没有别人同时改它的时候才成立。
//  缓存和锁必须住在一起，分开就一定会有一个先坏掉。
//  （锁的实现在 lock.hpp，那儿讲的是"为什么必须是操作系统的文件锁"。）
//
//  【和操作系统的页缓存有什么关系】
//  操作系统也有页缓存，为什么不干脆交给它？
//  因为它不知道数据库的语义：它只能猜"这页大概还会用到"
//  （LRU），而我们知道"刚插入的那页马上还要写"。
//  更重要的是——数据库需要控制**什么时候真正落盘**（提交时才落），
//  这个权利必须在自己手里。交给操作系统就没有这回事了。
//  （SQLite 也得自己管，理由一模一样。）
//
//  【这一层和 page.hpp 的分工】
//  page.hpp 管"这 4096 字节里，第几个字节是什么意思"，
//  这个文件管"这 4096 字节从哪来、什么时候写回去"。
//  换存储介质（加压缩、加内存盘）只动这里；改文件格式只动那边。
// ============================================================

#include <cstddef>
#include <cstdint>
#include <cstdio>
#include <string>
#include <vector>

#include "journal.hpp"
#include "lock.hpp"
#include "page.hpp"

// 测试用的崩溃开关。
//
// 【为什么这种东西会出现在产品代码里】
// 因为"崩溃之后还能不能恢复"是这一阶段唯一没法用正常手段验证的事：
// 正常跑完的程序不会崩，而想让它崩就得真的把它杀掉——那要靠
// 掐进程、抢时序，测出来是一个**有时过有时不过**的测试。
// 一个会偶尔失败的测试比没有测试更糟：它训练人不信测试。
//
// 所以崩溃点做成一个显式的开关。它不是"模拟崩溃"，它就是崩溃——
// 走到那一步直接 _Exit，不跑任何析构、不刷任何缓冲，
// 和掉电、被 taskkill 是一模一样的状态。
enum class CrashPoint {
    NONE,    // 正常
    COMMIT,  // 提交时：该写的页都写进库文件了，但日志还没删就死
    EXIT,    // 退出时：事务还开着就死（改动都还在缓存里）
};

class Pager {
public:
    // path 为空 = 内存库：数据只活在内存里，进程一退就没了。
    //
    // 【为什么要有这个模式】
    // 两个用处：
    //   1. 测试。跑一遍 SQL 脚本，结果必须每次都一样。
    //      要是默认就往文件里写，第二次跑就会看到上次的数据，
    //      基准输出根本没法写。
    //   2. 它就是 SQLite 的 `:memory:`，本来就是个正经功能。
    //
    // 顺带它还逼着这一层的接口只跟"页"打交道，不跟"文件"打交道——
    // 这个接口约束本身就是好的（见下面 Handle 的说明）。
    //
    // 【打开之前会先做一次崩溃恢复】如果上次没走完（日志文件还在），
    // 先照日志把库文件退回去，再当成普通文件打开。顺序不能反：
    // 一旦先算好了页数、读进了缓存，就再也说不清"现在这个状态是
    // 崩溃留下的，还是本来就该这样"。见 journal.hpp。
    //
    // 【阶段 6 起，最前面又多了一步：给库上锁】顺序同样是死的：
    // **锁 → 恢复 → 打开**。恢复是一次真正的写，两个进程同时
    // 恢复同一个库就是两个写者——那正是这一阶段要挡的事，
    // 所以锁必须比它更早。见 lock.hpp。
    //
    // lockWaitMs 是抢不到锁时愿意等多久（0 = 立刻放弃、报错）。
    explicit Pager(const std::string& path,
                   CrashPoint crash = CrashPoint::NONE, int lockWaitMs = 0);
    ~Pager();

    // 页缓存里的每个位置都被一个 Handle 借用着，复制一个 Pager
    // 会让两个对象都以为自己在管这些帧。直接禁掉，编译器帮我们拦。
    Pager(const Pager&) = delete;
    Pager& operator=(const Pager&) = delete;

    // ------------------------------------------------------------
    //  Handle —— 借一页出来用
    // ------------------------------------------------------------
    //
    // ★ 这是本文件里唯一需要理解的东西 ★
    //
    // 【为什么不能直接返回 char*】
    // 因为"这一页现在被借用着，不许踢出去"这件事必须有人记着。
    // 直接给 char* 的话，调用方正在往这页里写，缓存另一次
    // 读别的页时把这一页踢出去、位置让给了别的页——
    // 于是刚才那个 char* 还在原地写，写的却是另一个页的内容。
    // **不会崩**，只是数据静悄悄地坏掉。这是最难查的一类 bug。
    //
    // Handle 就是"借条"：构造时 pin 住这一页，析构时还回去。
    // 这是 RowScope / EnvironmentGuard 那一套（RAII）的第三次应用——
    // 这次管的东西更底层，但道理完全一样：
    // **让"配对的操作"由语言来保证，而不是由记性来保证。**
    //
    //   {
    //       Pager::Handle h = pager.get(3);
    //       ... 用 h.data() 读写 ...
    //       h.markDirty();          // 改过了，回头要写回磁盘
    //   }                            // <- 出了这个作用域自动 unpin
    class Handle {
    public:
        Handle() = default;
        Handle(Pager* pager, uint32_t pageNo, char* data, size_t frameIndex);
        ~Handle();

        // 只能搬，不能抄。两个 Handle 指着同一页的话，
        // 析构时会 unpin 两次，pin 计数就乱了。
        // （和 unique_ptr 是同一个道理的同一个写法。）
        Handle(Handle&& other) noexcept;
        Handle& operator=(Handle&& other) noexcept;
        Handle(const Handle&) = delete;
        Handle& operator=(const Handle&) = delete;

        char* data() const { return data_; }
        uint32_t pageNo() const { return pageNo_; }

        // 声明"我改过这一页"。**必须显式调用**，不自动。
        //
        // 【为什么不自动标脏】因为绝大多数取页是**只读**的
        //（全表扫描把每一页都读一遍）。自动标脏的话，扫一遍
        // 整张表就会把所有页都标成待写回，接着一次 flush
        // 把没改过的页重写一遍——磁盘白写，而且是在最不该慢的时候慢。
        // 一次调用换掉这些，值。
        //
        // 【阶段 5 起，它还兼任一道检查】改一个"事务开始前就存在、
        // 而这个事务里又没记进日志"的页，会当场抛异常。
        // 那不是一条普通的错误信息，是**代码写错了**的信号：
        // 说明有人用 get() 拿了页然后改它，绕过了 getForWrite。
        //
        // 让这种错误在这里当场炸掉，而不是等到某次回滚之后
        // 数据莫名其妙地不对——那时候离肇事现场已经十万八千里了。
        void markDirty() const;

        // 借条有效吗（没被搬走过）
        explicit operator bool() const { return pager_ != nullptr; }

    private:
        // 还掉这一页。析构和移动赋值都要用，所以单独一个函数——
        // 移动赋值里直接调 `this->~Handle()` 也能跑，但读的人
        // 得停下来想"这里析构了，后面那个析构怎么办"，不值得。
        void release();

        Pager* pager_ = nullptr;
        uint32_t pageNo_ = INVALID_PAGE;
        char* data_ = nullptr;

        // 直接记住"我在缓存里的第几格"。
        //
        // 【为什么不让析构去 frames_ 里找】找一遍是 64 次比较，
        // 而 unpin 发生在每一次取页之后——它是这个程序里最热的一行。
        // 另外这样也顺带说明了一件事：Handle 记住的是**格子**
        // 而不是页号，所以即使页号被换掉了（不可能，pin 着呢），
        // 它还回去的也是自己那一格。
        size_t frameIndex_ = 0;
    };

    // 取第 pageNo 页。页号必须在 [0, pageCount()) 里——
    // 越界会抛 AcornError。想要新页用 allocatePage()。
    //
    // ★ 只读用它。要改这一页，用下面的 getForWrite ★
    Handle get(uint32_t pageNo);

    // ------------------------------------------------------------
    //  取一页来改（阶段 5）
    // ------------------------------------------------------------
    //
    // 和 get() 唯一的区别是：**它会在日志里记下这一页现在长什么样。**
    //
    // 【为什么必须区分"读"和"写"】
    // 因为日志要的是"改动之前的样子"，而那个样子只有在这一页
    // 还没被任何人碰过的时候才拿得到。要是等到 markDirty 的时候
    // 再记，调用方十有八九已经写进去了——记下来的是改完的样子，
    // 回滚会把"改完的样子"当成"原来的样子"写回去，等于没退。
    // 而且**不会报错**，只是回滚之后数据看着有点不对。
    //
    // 【为什么不能干脆在 get() 里记】
    // 因为绝大多数取页是只读的（全表扫描把每一页都读一遍）。
    // 在 get() 里记的话，扫一张 1000 页的表就会写一份 4MB 的日志，
    // 而这一趟什么都没改。日志的大小必须和"改了多少"成正比，
    // 不能和"读了多少"成正比。
    //
    // 【同一页在一个事务里只会真记一次】重复调用是空操作
    //（判断在 Journal 里）。所以"改之前先 getForWrite"可以无脑写，
    // 不用自己去记哪几页已经记过了。
    Handle getForWrite(uint32_t pageNo);

    // ------------------------------------------------------------
    //  事务（阶段 5）
    // ------------------------------------------------------------
    //
    // 这一层实现的是**原子性**：一个事务里的改动要么全生效，要么全不生效。
    // 保证来自回滚日志，见 journal.hpp。
    //
    // 【它**不**保证持久性】提交时确实会把页刷到磁盘（flush + fsync），
    // 所以"提交了就丢不了"是成立的。但没提交的改动**可能**会被
    // 缓存淘汰顺手写进文件——那没关系，日志会把它们退回去。
    // 这正是"日志在先"这条顺序的全部意义：允许脏页提前落盘。
    //
    // 【这一层不知道 SQL，只知道页】所以事务的边界（BEGIN/COMMIT/ROLLBACK）
    // 是 Database 和 main 的事，这里只提供"开/提交/回滚"三个动作。

    void beginTransaction(bool implicit = false);
    void commitTransaction();
    void rollbackTransaction();
    bool inTransaction() const { return inTransaction_; }

    // 这个事务是"用户敲了 BEGIN"开的，还是"某条语句要改数据"自动开的。
    // 见 getForWrite 里那段自动提交的说明。main 靠它决定语句跑完之后
    // 要不要替用户提交——替用户提交一个 BEGIN 开的事务是灾难。
    bool transactionIsImplicit() const { return transactionImplicit_; }

    // 这个事务里已经记了多少页（调试用：回滚要退多少东西）
    size_t journalRecordCount() const { return journal_.recordCount(); }

    // ------------------------------------------------------------
    //  分配和释放
    // ------------------------------------------------------------

    // 要一个全新的、内容全 0 的页。返回的 Handle 已经标脏。
    //
    // 【为什么返回 Handle 而不是页号】
    // 因为调用方拿到页号之后必然马上要写它，中间只要插进任何一次
    // 别的取页操作，这一页就可能被踢出缓存——写进去的东西就没了。
    // 直接连着借条一起给，就没有这个缝。
    Handle allocatePage();

    // 把一页还回空闲链，下次 allocatePage 会优先复用它。
    //
    // 【为什么必须有这个】不然文件只会变大。删掉一张表、
    // 它的数据页就再没人用了，但那 4KB 还在文件里占着。
    // 空闲链就是"哪些页现在没人用"的答案。
    void freePage(uint32_t pageNo);

    // 把缓存里所有脏页写回磁盘。
    // 【注意它不清缓存】——写回和丢弃是两件事，
    // 清缓存会让紧接着的查询重新读一遍磁盘，白慢。
    void flush();

    // 文件里一共有多少页（含第 0 页）。
    // 这就是文件的字节数除以 4096——**不另外存一份**，
    // 见 page.hpp 里关于"别存能算出来的东西"那段。
    uint32_t pageCount() const { return pageCount_; }

    bool inMemory() const { return path_.empty(); }
    const std::string& path() const { return path_; }

    // ------------------------------------------------------------
    //  锁（阶段 6）
    // ------------------------------------------------------------
    //
    // 这一层实现的是**隔离性**里最粗的那一档：一个库同时只能有
    // 一个写者，或者若干个读者，二者不能并存。机制是操作系统给的
    // 文件锁，见 lock.hpp。
    //
    // 【为什么是"最粗的那一档"】因为我们锁的是**整个库**，
    // 不是某一张表、某一行。粒度越粗，实现越简单、能并发的人越少。
    // 粒度细到"按行加锁"就是另一个量级的东西了（要锁管理器、
    // 要死锁检测），那是把 MVCC 那一套补上之后才谈得上的事。
    //
    // 【它保证什么】不会有两个进程同时写同一个库（改一半被覆盖），
    // 也不会有进程读到别人写了一半的页。
    // 【它不保证什么】读会挡住写、写会挡住读——没有快照隔离。
    // 要"读的时候别人照样能写"，得上 MVCC。
    LockMode lockMode() const { return lock_.mode(); }
    bool lockHeld() const { return lock_.held(); }

    // 给 .info 用的一句话（"独占"/"共享"/"没有"）。
    std::string lockState() const;

    // 只在测试和调试时看：缓存里现在装着哪些页、几页是脏的。
    std::string cacheStats() const;

private:
    // 缓存里的一个格子。
    //
    // data 不在这里面——所有格子的数据连成一大块（pool_），
    // 每个 Frame 记自己的下标。理由见 pool_ 的注释。
    struct Frame {
        uint32_t pageNo = INVALID_PAGE;
        bool dirty = false;
        bool pinned = false;
        bool referenced = false;  // 时钟算法用的"最近被碰过"位
    };

    Frame& load(uint32_t pageNo);
    size_t pickVictim();
    char* dataSlot(size_t index) { return pool_.data() + index * PAGE_SIZE; }
    const char* dataSlot(size_t index) const {
        return pool_.data() + index * PAGE_SIZE;
    }

    // 事务没开就开一个（自动提交那一套）。凡是要改动文件状态的地方
    // 都得先调它一声——详细说明在 pager.cpp 里。
    void ensureTransaction();

    // 确认自己手上还拿着"读的资格"。没有就去拿，拿不到就抛。
    // 取任何一页之前都要过这一关——详细说明在 pager.cpp 里。
    void ensureSharedLock();

    // 确认自己手上拿着"写的资格"（独占锁）。没有就去拿，
    // 或者从共享升级过去。拿不到就抛——详细说明在 pager.cpp 里。
    void ensureExclusiveLock();

    void readFromDisk(uint32_t pageNo, char* out);
    void writeToDisk(uint32_t pageNo, const char* data);

    // 把库文件已经写下去的东西真正交给磁盘。
    // 提交时用它——那是"提交了就不会丢"这句话唯一的依据。
    void syncFile();

    // 一页都不留，全部作废（回滚之后用）。
    // 【为什么整块扔掉，而不是挑着扔】因为回滚改的是文件，
    // 缓存里那些页现在装的是**已经不存在的**内容。挑着扔要判断
    // "这一页受不受影响"，而那个判断错了就会读到脏数据。
    // 全扔是 O(1) 的判断，代价只是下次查询重新读一遍盘。
    void invalidateCache();

    // 空闲链的头存在第 0 页里。见下面的实现说明。
    uint32_t freeListHead();
    void setFreeListHead(uint32_t pageNo);

    std::string path_;
    std::FILE* file_ = nullptr;  // 空 = 内存库。见 open 那一段的说明

    // ---- 锁（阶段 6）----
    //
    // 【为什么锁住在这里，而不是 Database 那一层】
    // 因为它是"这份页缓存现在还算不算数"的前提，而页缓存是这一层的。
    // 而且 Pager 是唯一碰文件的一层——锁也是文件上的东西，
    // 放别处就成了跨层。
    FileLock lock_;
    int lockWaitMs_ = 0;

    // 内存库的"磁盘"：一个按页铺开的字节数组。换页时正确地增长。
    // 【注意它只在写回的时候用到】——内存库并不是"不走缓存"，
    // 而是"缓存写回的目标是内存不是文件"。所以除了 readFromDisk /
    // writeToDisk 这两个函数，别的地方完全不用区分两种模式。
    std::vector<char> memory_;

    // 所有格子的数据连成一大块，一次分配。
    //
    // 【为什么不给每个 Frame 一个 vector<char>】
    // 那样缓存变大的时候（以后要支持配置）会有 64 次小分配，
    // 更要紧的是：Frame 存在 vector<Frame> 里会搬家，
    // 而"指向某一帧数据的指针"必须一直有效（Handle 拿着它）。
    // 数据放在一个**不随 Frame 数组搬家**的地方，这个约束
    // 就自动满足了——不用去分析 vector 什么时候扩容。
    std::vector<char> pool_;

    std::vector<Frame> frames_;
    size_t clockHand_ = 0;

    uint32_t pageCount_ = 0;

    // ---- 事务（阶段 5）----
    Journal journal_;

    bool inTransaction_ = false;
    bool transactionImplicit_ = false;

    // 事务开始时库文件有几页。
    //
    // 【为什么这儿还要存一份】Journal 里已经有一份了（在日志头里）。
    // 因为回滚要用它**两次**：一次是让 Journal 交出旧内容，
    // 一次是决定缓存里哪些页已经作废。缓存那一半不该跑去问日志。
    // 两份值是同一个来源（beginTransaction 里一起写），不会对不上。
    uint32_t journalPageCount_ = 0;

    CrashPoint crashPoint_ = CrashPoint::NONE;
};

// 缓存开多大。64 页 × 4KB = 256KB。
