-- SQL 三值逻辑的真值表。整个阶段 1 最容易写错的地方。
CREATE TABLE t (id INT);
INSERT INTO t VALUES (1);
SELECT TRUE AND NULL, FALSE AND NULL, TRUE OR NULL, FALSE OR NULL, NOT NULL FROM t;
-- WHERE 只放行"确定成真"的行，NULL 一律滤掉
SELECT * FROM t WHERE NULL;
SELECT * FROM t WHERE NOT NULL;
SELECT * FROM t WHERE TRUE AND NULL;
SELECT * FROM t WHERE FALSE AND NULL;
-- 这两个能出结果：短路之后结论是确定的
SELECT * FROM t WHERE TRUE OR NULL;
